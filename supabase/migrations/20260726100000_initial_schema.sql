-- UMKM Desa Masaran: initial schema
-- Password is intentionally managed by Supabase Auth (auth.users), never by public tables.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('admin', 'umkm')),
  username text unique,
  login_email text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint admin_has_username check (
    (role = 'admin' and username is not null and login_email is not null)
    or role = 'umkm'
  )
);

create unique index if not exists profiles_username_lower_key
  on public.profiles (lower(username))
  where username is not null;

create table if not exists public.umkm (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles (id) on delete restrict,
  slug text not null unique,
  nama text not null,
  pemilik text not null,
  rt text,
  rw text,
  dukuh text,
  dusun text,
  alamat_lengkap text,
  no_wa text not null,
  instagram text,
  tiktok text,
  facebook text,
  shopee text,
  tokopedia text,
  google_maps text,
  keunggulan1 text,
  keunggulan2 text,
  keunggulan3 text,
  keunggulan4 text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint umkm_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table if not exists public.kategori (
  id bigint generated by default as identity primary key,
  nama text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists kategori_nama_lower_key
  on public.kategori (lower(nama));

create table if not exists public.umkm_kategori (
  umkm_id bigint not null references public.umkm (id) on delete cascade,
  kategori_id bigint not null references public.kategori (id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (umkm_id, kategori_id)
);

create table if not exists public.produk (
  id bigint generated by default as identity primary key,
  id_umkm bigint not null references public.umkm (id) on delete cascade,
  nama text not null,
  deskripsi text,
  harga numeric(12, 2) not null check (harga >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists produk_id_umkm_idx on public.produk (id_umkm);

create table if not exists public.umkm_images (
  id bigint generated by default as identity primary key,
  umkm_id bigint not null references public.umkm (id) on delete cascade,
  slot text not null check (slot in ('logo', 'gambar_1', 'gambar_2', 'gambar_3')),
  storage_path text not null unique,
  alt_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (umkm_id, slot)
);

create table if not exists public.desa (
  id smallint primary key default 1 check (id = 1),
  alamat text,
  no_telepon text,
  email text,
  tentang text,
  google_maps text,
  facebook text,
  instagram text,
  tiktok text,
  youtube text,
  balai_desa_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.desa (id) values (1) on conflict (id) do nothing;

create table if not exists public.desa_images (
  id bigint generated by default as identity primary key,
  desa_id smallint not null default 1 references public.desa (id) on delete cascade,
  urutan smallint not null check (urutan between 1 and 6),
  storage_path text not null unique,
  deskripsi text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (desa_id, urutan)
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.owns_umkm(target_umkm_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.umkm
    where id = target_umkm_id and user_id = auth.uid()
  );
$$;

create or replace function public.can_manage_umkm_storage(object_name text)
returns boolean
language sql
stable
security definer
set search_path = public, storage
as $$
  select public.is_admin() or exists (
    select 1
    from public.umkm
    where user_id = auth.uid()
      and (storage.foldername(object_name))[1] = 'umkm'
      and (storage.foldername(object_name))[2] = id::text
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.owns_umkm(bigint) to anon, authenticated;
grant execute on function public.can_manage_umkm_storage(text) to anon, authenticated;

