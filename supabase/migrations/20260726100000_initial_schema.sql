create policy "Profiles can be read by their owner or an admin"
  on public.profiles for select
  using (id = auth.uid() or public.is_admin());

create policy "Public can read UMKM"
  on public.umkm for select using (true);
create policy "Admins manage every UMKM"
  on public.umkm for all
  using (public.is_admin()) with check (public.is_admin());
create policy "UMKM owner updates own profile"
  on public.umkm for update
  using (public.owns_umkm(id)) with check (user_id = auth.uid());

