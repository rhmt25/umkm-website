insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'umkm-media',
  'umkm-media',
  true,
  2097152,
  array['image/jpeg', 'image/png']
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

create policy "Public can view UMKM media"
  on storage.objects for select
  using (bucket_id = 'umkm-media');
create policy "Admins and owners upload UMKM media"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'umkm-media'
    and public.can_manage_umkm_storage(name)
  );
create policy "Admins and owners update UMKM media"
  on storage.objects for update to authenticated
  using (bucket_id = 'umkm-media' and public.can_manage_umkm_storage(name))
  with check (bucket_id = 'umkm-media' and public.can_manage_umkm_storage(name));
create policy "Admins and owners delete UMKM media"
  on storage.objects for delete to authenticated
  using (bucket_id = 'umkm-media' and public.can_manage_umkm_storage(name));
